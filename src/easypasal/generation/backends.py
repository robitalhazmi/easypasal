"""Pluggable LLM generation backends: llama.cpp, Ollama, OpenAI-compatible, and Mock."""

from __future__ import annotations

import logging
import re
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import httpx

from easypasal.generation.prompts import (
    STANDARD_ABSTAIN_EN,
    STANDARD_ABSTAIN_ID,
    detect_language,
)

logger = logging.getLogger("easypasal.generation.backends")

DEFAULT_GGUF_REPO: str = "Qwen/Qwen2.5-1.5B-Instruct-GGUF"
DEFAULT_GGUF_FILE: str = "qwen2.5-1.5b-instruct-q4_k_m.gguf"
DEFAULT_OLLAMA_MODEL: str = "qwen2.5:1.5b"


@dataclass
class LLMGenerationResult:
    """Raw output generated by an LLM backend."""

    text: str
    prompt_tokens: int = 0
    completion_tokens: int = 0
    latency_ms: float = 0.0
    model_name: str = ""


class GeneratorBackend(Protocol):
    """Protocol defining the interface for LLM text generators."""

    @property
    def model_name(self) -> str:
        """Name or identifier of the underlying model."""
        ...

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        """Generate response text for the provided input prompt."""
        ...


class MockGeneratorBackend:
    """Deterministic offline generator for testing and CI pipelines.

    Generates grounded answers citing retrieved passages or produces standard
    abstentions for out-of-corpus queries without requiring external LLM weights.
    """

    def __init__(self, model_name: str = "mock-generator") -> None:
        self._model_name = model_name

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        _ = (temperature, max_tokens, stop)
        start_time = time.perf_counter()
        lang = detect_language(prompt)

        # 1. Detect Out-of-Corpus Questions in Prompt
        ooc_patterns = [
            r"hak guna bangunan",
            r"hgb",
            r"tanah",
            r"helm",
            r"tilang",
            r"lalu lintas",
            r"rendang",
            r"resep",
            r"memasak",
            r"masakan",
        ]
        is_ooc = any(re.search(pat, prompt, re.IGNORECASE) for pat in ooc_patterns)

        # Check if context block has no documents
        has_no_docs = "TIDAK ADA KONTEKS" in prompt or "--- DOKUMEN" not in prompt

        if is_ooc or has_no_docs:
            answer = STANDARD_ABSTAIN_EN if lang == "en" else STANDARD_ABSTAIN_ID
            latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
            return LLMGenerationResult(
                text=answer,
                prompt_tokens=len(prompt.split()),
                completion_tokens=len(answer.split()),
                latency_ms=latency_ms,
                model_name=self._model_name,
            )

        # 2. In-Corpus Question: Synthesize answer with top passage citation
        doc_matches = re.findall(
            r"---\s*DOKUMEN\s+\d+:\s*(.*?)(?:\s*\(Status:[^\)]*\))?\s*---", prompt
        )
        citation_label = doc_matches[0].strip() if doc_matches else "POJK Terkait"

        # Extract text snippets following the first document header
        context_body = ""
        context_match = re.search(
            r"---\s*DOKUMEN\s+1:.*?\n(.*?)(?:--- DOKUMEN|\n\n<question>|$)", prompt, re.DOTALL
        )
        if context_match:
            lines = [
                line.strip()
                for line in context_match.group(1).splitlines()
                if line.strip() and not line.startswith("[")
            ]
            context_body = " ".join(lines[:2])

        if lang == "en":
            answer = (
                f"Based on [{citation_label}], the regulation provides: {context_body or 'the relevant statutory provision establishes the compliance obligations'}. "
                f"This requirement is formally grounded in [{citation_label}]."
            )
        else:
            answer = (
                f"Berdasarkan [{citation_label}], diatur bahwa: {context_body or 'ketentuan yang bersangkutan menetapkan kewajiban kepatuhan bagi pihak terkait'}. "
                f"Dasar hukum ketentuan ini tercantum dalam [{citation_label}]."
            )

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
        return LLMGenerationResult(
            text=answer,
            prompt_tokens=len(prompt.split()),
            completion_tokens=len(answer.split()),
            latency_ms=latency_ms,
            model_name=self._model_name,
        )


class OllamaBackend:
    """Ollama HTTP client backend for local CPU/GPU serving."""

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        model_name: str = DEFAULT_OLLAMA_MODEL,
        timeout: float = 60.0,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self._model_name = model_name
        self.client = httpx.Client(base_url=self.base_url, timeout=timeout)

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        start_time = time.perf_counter()
        payload = {
            "model": self._model_name,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": temperature,
                "num_predict": max_tokens,
                "stop": stop or [],
            },
        }

        try:
            resp = self.client.post("/api/generate", json=payload)
            resp.raise_for_status()
            data = resp.json()
            text = data.get("response", "").strip()
            prompt_tokens = data.get("prompt_eval_count", 0)
            completion_tokens = data.get("eval_count", 0)
        except Exception as e:
            logger.error("Ollama generation failed: %s", e)
            raise

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
        return LLMGenerationResult(
            text=text,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
        )


class OpenAICompatibleBackend:
    """Client for local OpenAI-compatible endpoints (vLLM, llama-server, LocalAI)."""

    def __init__(
        self,
        base_url: str = "http://localhost:8000/v1",
        model_name: str = "local-model",
        api_key: str = "EMPTY",
        timeout: float = 60.0,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self._model_name = model_name
        headers = {"Authorization": f"Bearer {api_key}"}
        self.client = httpx.Client(base_url=self.base_url, headers=headers, timeout=timeout)

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        start_time = time.perf_counter()
        payload = {
            "model": self._model_name,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": temperature,
            "max_tokens": max_tokens,
            "stop": stop,
        }

        resp = self.client.post("/chat/completions", json=payload)
        resp.raise_for_status()
        data = resp.json()

        choices = data.get("choices", [])
        text = choices[0]["message"]["content"].strip() if choices else ""
        usage = data.get("usage", {})

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
        return LLMGenerationResult(
            text=text,
            prompt_tokens=usage.get("prompt_tokens", 0),
            completion_tokens=usage.get("completion_tokens", 0),
            latency_ms=latency_ms,
            model_name=self._model_name,
        )


class LlamaCppBackend:
    """In-process GGUF generator running on CPU via llama-cpp-python."""

    def __init__(
        self,
        model_path: Path | str | None = None,
        repo_id: str = DEFAULT_GGUF_REPO,
        filename: str = DEFAULT_GGUF_FILE,
        n_ctx: int = 2048,
        n_threads: int | None = None,
    ) -> None:
        from llama_cpp import Llama

        if model_path is None:
            from huggingface_hub import hf_hub_download

            cache_dir = Path.home() / ".cache" / "easypasal" / "models"
            cache_dir.mkdir(parents=True, exist_ok=True)
            logger.info("Downloading GGUF weights %s/%s to %s...", repo_id, filename, cache_dir)
            resolved_path = hf_hub_download(
                repo_id=repo_id,
                filename=filename,
                local_dir=str(cache_dir),
            )
            self.model_path = Path(resolved_path)
        else:
            self.model_path = Path(model_path)

        if not self.model_path.exists():
            raise FileNotFoundError(f"GGUF model not found at {self.model_path}")

        logger.info("Initializing Llama model from %s (n_ctx=%d)...", self.model_path, n_ctx)
        self._llm = Llama(
            model_path=str(self.model_path),
            n_ctx=n_ctx,
            n_threads=n_threads,
            verbose=False,
        )
        self._model_name = self.model_path.stem

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        start_time = time.perf_counter()
        res = self._llm.create_completion(
            prompt=prompt,
            temperature=temperature,
            max_tokens=max_tokens,
            stop=stop or ["</answer>", "User:", "\n\nUser:"],
            stream=False,
        )

        prompt_tokens = 0
        completion_tokens = 0
        if isinstance(res, dict):
            choice = res["choices"][0]
            text = str(choice.get("text", "")).strip()
            usage = res.get("usage")
            if isinstance(usage, dict):
                prompt_tokens = int(usage.get("prompt_tokens", 0))
                completion_tokens = int(usage.get("completion_tokens", 0))
        else:
            text = ""

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
        return LLMGenerationResult(
            text=text,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
        )


def get_generator_backend(
    provider: str = "auto",
    model_name: str | None = None,
    model_path: Path | str | None = None,
    base_url: str | None = None,
) -> GeneratorBackend:
    """Factory creating a generator backend based on available infrastructure.

    Providers:
        - 'llamacpp': In-process llama.cpp execution (GGUF).
        - 'ollama': Local Ollama HTTP daemon.
        - 'openai': OpenAI-compatible HTTP endpoint.
        - 'mock': Offline deterministic generator for tests and CI.
        - 'auto': Attempts local Ollama/LlamaCpp, falling back gracefully to Mock.
    """
    if provider == "mock":
        return MockGeneratorBackend(model_name=model_name or "mock-generator")

    if provider == "ollama":
        return OllamaBackend(
            base_url=base_url or "http://localhost:11434",
            model_name=model_name or DEFAULT_OLLAMA_MODEL,
        )

    if provider == "openai":
        return OpenAICompatibleBackend(
            base_url=base_url or "http://localhost:8000/v1",
            model_name=model_name or "local-model",
        )

    if provider == "llamacpp":
        return LlamaCppBackend(
            model_path=model_path,
            filename=model_name or DEFAULT_GGUF_FILE,
        )

    # Provider == 'auto': Check local Ollama server first
    try:
        check_url = (base_url or "http://localhost:11434").rstrip("/") + "/api/tags"
        resp = httpx.get(check_url, timeout=0.8)
        if resp.status_code == 200:
            logger.info("Auto-detected active Ollama service at %s", check_url)
            return OllamaBackend(
                base_url=base_url or "http://localhost:11434",
                model_name=model_name or DEFAULT_OLLAMA_MODEL,
            )
    except Exception:
        pass

    # Check if explicit GGUF path is available on disk
    if model_path and Path(model_path).exists():
        try:
            return LlamaCppBackend(model_path=model_path)
        except Exception as e:
            logger.warning("Failed to initialize LlamaCppBackend: %s", e)

    # Default auto fallback to MockGeneratorBackend
    logger.info("No active local LLM daemon detected; using MockGeneratorBackend.")
    return MockGeneratorBackend(model_name=model_name or "mock-generator")
