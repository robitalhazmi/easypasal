class MockGeneratorBackend:
    """Deterministic offline generator for testing and CI pipelines.

    Generates grounded answers citing retrieved passages or produces standard
    abstentions for out-of-corpus queries without requiring external LLM weights.
    """

    def __init__(self, model_name: str = "mock-generator") -> None:
        self._model_name = model_name

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        _ = (temperature, max_tokens, stop)
        start_time = time.perf_counter()
        lang = detect_language(prompt)

        # 1. Detect Out-of-Corpus Questions in Prompt (evaluate strictly on question block)
        q_match = re.search(r"<question>(.*?)</question>", prompt, re.DOTALL)
        eval_text = q_match.group(1) if q_match else prompt

        ooc_patterns = [
            r"hak guna bangunan",
            r"hgb",
            r"tanah",
            r"helm",
            r"tilang",
            r"lalu lintas",
            r"rendang",
            r"resep",
            r"memasak",
            r"masakan",
        ]
        is_ooc = any(re.search(pat, eval_text, re.IGNORECASE) for pat in ooc_patterns)

        # Check if context block has no documents
        has_no_docs = "TIDAK ADA KONTEKS" in prompt or "--- DOKUMEN" not in prompt

        if is_ooc or has_no_docs:
            answer = STANDARD_ABSTAIN_EN if lang == "en" else STANDARD_ABSTAIN_ID
            elapsed = time.perf_counter() - start_time
            latency_ms = round(elapsed * 1000, 2)
            completion_tokens = len(answer.split())
            tokens_per_second = round(completion_tokens / elapsed, 2) if elapsed > 0 else 50.0
            return LLMGenerationResult(
                text=answer,
                prompt_tokens=len(prompt.split()),
                completion_tokens=completion_tokens,
                latency_ms=latency_ms,
                model_name=self._model_name,
                tokens_per_second=tokens_per_second,
            )

        # 2. In-Corpus Question: Synthesize answer with top passage citation
        doc_matches = re.findall(
            r"---\s*DOKUMEN\s+\d+:\s*(.*?)(?:\s*\(Status:[^\)]*\))?\s*---", prompt
        )
        citation_label = doc_matches[0].strip() if doc_matches else "POJK Terkait"

        # Extract text snippets following the first document header
        context_body = ""
        context_match = re.search(
            r"---\s*DOKUMEN\s+1:.*?\n(.*?)(?:--- DOKUMEN|\n\n<question>|$)", prompt, re.DOTALL
        )
        if context_match:
            lines = [
                line.strip()
                for line in context_match.group(1).splitlines()
                if line.strip() and not line.startswith("[")
            ]
            context_body = " ".join(lines[:2])

        if lang == "en":
            answer = (
                f"Based on [{citation_label}], the regulation provides: {context_body or 'the relevant statutory provision establishes the compliance obligations'}. "
                f"This requirement is formally grounded in [{citation_label}]."
            )
        else:
            answer = (
                f"Berdasarkan [{citation_label}], diatur bahwa: {context_body or 'ketentuan yang bersangkutan menetapkan kewajiban kepatuhan bagi pihak terkait'}. "
                f"Dasar hukum ketentuan ini tercantum dalam [{citation_label}]."
            )

        elapsed = time.perf_counter() - start_time
        latency_ms = round(elapsed * 1000, 2)
        completion_tokens = len(answer.split())
        tokens_per_second = round(completion_tokens / elapsed, 2) if elapsed > 0 else 50.0
        return LLMGenerationResult(
            text=answer,
            prompt_tokens=len(prompt.split()),
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
            tokens_per_second=tokens_per_second,
        )


class OllamaBackend:
    """Ollama HTTP client backend for local CPU/GPU serving."""

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        model_name: str = DEFAULT_OLLAMA_MODEL,
        timeout: float = 60.0,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self._model_name = model_name
        self.client = httpx.Client(base_url=self.base_url, timeout=timeout)

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        start_time = time.perf_counter()
        rep_penalty_env = os.getenv("EASYPASAL_REPETITION_PENALTY")
        rep_penalty = float(rep_penalty_env) if rep_penalty_env else 1.15

        payload = {
            "model": self._model_name,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": temperature,
                "num_predict": max_tokens,
                "stop": stop or [],
                "repeat_penalty": rep_penalty,
            },
        }

        try:
            resp = self.client.post("/api/generate", json=payload)
            resp.raise_for_status()
            data = resp.json()
            raw_text = data.get("response", "").strip()
            text = trim_incomplete_sentence(raw_text)
            prompt_tokens = data.get("prompt_eval_count", 0)
            completion_tokens = data.get("eval_count", 0)
        except Exception as e:
            logger.error("Ollama generation failed: %s", e)
            raise

        elapsed = time.perf_counter() - start_time
        latency_ms = round(elapsed * 1000, 2)
        tokens_per_second = (
            round(completion_tokens / elapsed, 2) if elapsed > 0 and completion_tokens > 0 else 0.0
        )
        return LLMGenerationResult(
            text=text,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
            tokens_per_second=tokens_per_second,
        )


class OpenAICompatibleBackend:
    """Client for local OpenAI-compatible endpoints (vLLM, llama-server, LocalAI)."""

    def __init__(
        self,
        base_url: str = "http://localhost:8000/v1",
        model_name: str = "local-model",
        api_key: str = "EMPTY",
        timeout: float = 60.0,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self._model_name = model_name
        headers = {"Authorization": f"Bearer {api_key}"}
        self.client = httpx.Client(base_url=self.base_url, headers=headers, timeout=timeout)

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        start_time = time.perf_counter()
        payload = {
            "model": self._model_name,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": temperature,
            "max_tokens": max_tokens,
            "stop": stop,
            "frequency_penalty": 0.2,
            "presence_penalty": 0.2,
        }

        resp = self.client.post("/chat/completions", json=payload)
        resp.raise_for_status()
        data = resp.json()

        choices = data.get("choices", [])
        raw_text = choices[0]["message"]["content"].strip() if choices else ""
        text = trim_incomplete_sentence(raw_text)
        usage = data.get("usage", {})

        elapsed = time.perf_counter() - start_time
        latency_ms = round(elapsed * 1000, 2)
        completion_tokens = int(usage.get("completion_tokens", 0)) if isinstance(usage, dict) else 0
        tokens_per_second = (
            round(completion_tokens / elapsed, 2) if elapsed > 0 and completion_tokens > 0 else 0.0
        )
        return LLMGenerationResult(
            text=text,
            prompt_tokens=int(usage.get("prompt_tokens", 0)) if isinstance(usage, dict) else 0,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
            tokens_per_second=tokens_per_second,
        )


class TransformersBackend:
    """In-process PyTorch/Transformers causal language model backend.

    Supports dynamic GPU acceleration via torch.cuda and Hugging Face ZeroGPU (@spaces.GPU).
    """

    def __init__(
        self,
        model_name: str = DEFAULT_TRANSFORMERS_MODEL,
        device: str | None = None,
        torch_dtype: str | None = None,
        max_seq_length: int = 4096,
        lazy_load: bool = True,
    ) -> None:
        self._model_name = model_name
        self._device = device
        self._torch_dtype = torch_dtype
        self._max_seq_length = max_seq_length
        self._tokenizer: Any = None
        self._model: Any = None

        if not lazy_load:
            self._ensure_loaded()

    @property
    def model_name(self) -> str:
        return self._model_name

    def _ensure_loaded(self) -> None:
        if self._model is not None and self._tokenizer is not None:
            return

        try:
            import torch
            from transformers import AutoModelForCausalLM, AutoTokenizer
        except ImportError as exc:
            raise ImportError(
                "PyTorch and Transformers are required for TransformersBackend. "
                "Install them with: pip install torch transformers accelerate"
            ) from exc

        if self._tokenizer is None:
            logger.info("Loading Transformers tokenizer for %s...", self._model_name)
            self._tokenizer = AutoTokenizer.from_pretrained(
                self._model_name,
                trust_remote_code=True,
            )
            if self._tokenizer.pad_token is None:
                self._tokenizer.pad_token = self._tokenizer.eos_token

        if self._model is None:
            logger.info("Loading Transformers model for %s...", self._model_name)
            target_device = self._device
            if target_device is None:
                target_device = "cuda" if torch.cuda.is_available() else "cpu"

            dtype_map = {
                "float16": torch.float16,
                "bfloat16": torch.bfloat16,
                "float32": torch.float32,
            }
            chosen_dtype = dtype_map.get(
                self._torch_dtype or ("float16" if target_device == "cuda" else "float32"),
                torch.float32,
            )

            if target_device == "cuda":
                try:
                    self._model = AutoModelForCausalLM.from_pretrained(
                        self._model_name,
                        torch_dtype=chosen_dtype,
                        device_map="auto",
                        trust_remote_code=True,
                    )
                except Exception:
                    self._model = AutoModelForCausalLM.from_pretrained(
                        self._model_name,
                        torch_dtype=chosen_dtype,
                        trust_remote_code=True,
                    )
                    self._model.to("cuda")
            else:
                self._model = AutoModelForCausalLM.from_pretrained(
                    self._model_name,
                    torch_dtype=chosen_dtype,
                    low_cpu_mem_usage=True,
                    trust_remote_code=True,
                )
                self._model.to(target_device)

            self._model.eval()

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        self._ensure_loaded()
        try:
            import torch
        except ImportError as exc:
            raise ImportError("PyTorch is required for TransformersBackend.") from exc

        start_time = time.perf_counter()

        # Format input using chat template if system tags are present
        sys_match = re.search(r"<system>\s*(.*?)\s*</system>", prompt, re.DOTALL)
        user_body = re.sub(r"<system>\s*.*?\s*</system>", "", prompt, flags=re.DOTALL).strip()

        if sys_match and hasattr(self._tokenizer, "apply_chat_template"):
            messages = [
                {"role": "system", "content": sys_match.group(1).strip()},
                {"role": "user", "content": user_body},
            ]
            try:
                formatted_prompt = self._tokenizer.apply_chat_template(
                    messages,
                    tokenize=False,
                    add_generation_prompt=True,
                )
            except Exception:
                formatted_prompt = prompt
        else:
            formatted_prompt = prompt

        inputs = self._tokenizer(
            formatted_prompt,
            return_tensors="pt",
            truncation=True,
            max_length=self._max_seq_length,
        )

        model_device = getattr(self._model, "device", "cpu")
        inputs = {k: v.to(model_device) for k, v in inputs.items()}
        prompt_tokens = inputs["input_ids"].shape[1]

        do_sample = temperature > 0.01
        rep_penalty_env = os.getenv("EASYPASAL_REPETITION_PENALTY")
        rep_penalty = float(rep_penalty_env) if rep_penalty_env else 1.08

        no_repeat_ngram_env = os.getenv("EASYPASAL_NO_REPEAT_NGRAM_SIZE")
        no_repeat_ngram_size = int(no_repeat_ngram_env) if no_repeat_ngram_env else 0

        gen_kwargs: dict[str, Any] = {
            "max_new_tokens": max_tokens,
            "pad_token_id": self._tokenizer.pad_token_id,
            "eos_token_id": self._tokenizer.eos_token_id,
            "repetition_penalty": rep_penalty,
        }
        if no_repeat_ngram_size > 0:
            gen_kwargs["no_repeat_ngram_size"] = no_repeat_ngram_size
        if do_sample:
            gen_kwargs["temperature"] = temperature
            gen_kwargs["do_sample"] = True
            gen_kwargs["top_p"] = 0.95
        else:
            gen_kwargs["do_sample"] = False

        with torch.inference_mode():
            output_ids = self._model.generate(
                **inputs,
                **gen_kwargs,
            )

        generated_tokens = output_ids[0][prompt_tokens:]
        text = self._tokenizer.decode(generated_tokens, skip_special_tokens=True).strip()
        completion_tokens = len(generated_tokens)

        if stop:
            for s in stop:
                if s in text:
                    text = text.split(s)[0].strip()

        text = trim_incomplete_sentence(text)

        elapsed = time.perf_counter() - start_time
        latency_ms = round(elapsed * 1000, 2)
        tokens_per_second = (
            round(completion_tokens / elapsed, 2) if elapsed > 0 and completion_tokens > 0 else 0.0
        )

        return LLMGenerationResult(
            text=text,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
            tokens_per_second=tokens_per_second,
        )

    def close(self) -> None:
        """Release PyTorch model memory."""
        import gc

        self._model = None
        self._tokenizer = None
        gc.collect()
        with contextlib.suppress(Exception):
            import torch

            if torch.cuda.is_available():
                torch.cuda.empty_cache()


class HuggingFaceInferenceBackend:
    """Client for Hugging Face Serverless Inference API."""

    def __init__(
        self,
        model_name: str = DEFAULT_HF_MODEL,
        token: str | None = None,
        timeout: float = 60.0,
    ) -> None:
        try:
            from huggingface_hub import InferenceClient
        except ImportError as exc:
            raise ImportError(
                "huggingface_hub is required for HuggingFaceInferenceBackend."
            ) from exc

        self._model_name = model_name
        self.token = token or os.getenv("HF_TOKEN") or os.getenv("HUGGING_FACE_HUB_TOKEN")
        self.client = InferenceClient(model=self._model_name, token=self.token, timeout=timeout)

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        start_time = time.perf_counter()

        sys_match = re.search(r"<system>\s*(.*?)\s*</system>", prompt, re.DOTALL)
        user_body = re.sub(r"<system>\s*.*?\s*</system>", "", prompt, flags=re.DOTALL).strip()

        messages = []
        if sys_match:
            messages.append({"role": "system", "content": sys_match.group(1).strip()})
        messages.append({"role": "user", "content": user_body})

        try:
            resp = self.client.chat.completions.create(
                messages=messages,
                max_tokens=max_tokens,
                temperature=temperature,
                stop=stop,
            )
            choice = resp.choices[0]
            raw_text = (choice.message.content or "").strip()
            text = trim_incomplete_sentence(raw_text)
            prompt_tokens = getattr(
                getattr(resp, "usage", None), "prompt_tokens", len(prompt.split())
            )
            completion_tokens = getattr(
                getattr(resp, "usage", None), "completion_tokens", len(text.split())
            )
        except Exception as exc:
            logger.error("Hugging Face Inference API failed for %s: %s", self._model_name, exc)
            raise

        elapsed = time.perf_counter() - start_time
        latency_ms = round(elapsed * 1000, 2)
        tokens_per_second = (
            round(completion_tokens / elapsed, 2) if elapsed > 0 and completion_tokens > 0 else 0.0
        )
        return LLMGenerationResult(
            text=text,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
            tokens_per_second=tokens_per_second,
        )

    def close(self) -> None:
        """Close client if needed."""
        pass


class LlamaCppBackend:
    """In-process GGUF generator running on CPU via llama-cpp-python."""

    def __init__(
        self,
        model_path: Path | str | None = None,
        repo_id: str = DEFAULT_GGUF_REPO,
        filename: str = DEFAULT_GGUF_FILE,
        n_ctx: int = 8192,
        n_threads: int | None = None,
    ) -> None:
        from llama_cpp import Llama

        if model_path is None:
            from huggingface_hub import hf_hub_download

            cache_dir = Path.home() / ".cache" / "easypasal" / "models"
            cache_dir.mkdir(parents=True, exist_ok=True)
            logger.info("Downloading GGUF weights %s/%s to %s...", repo_id, filename, cache_dir)
            resolved_path = hf_hub_download(
                repo_id=repo_id,
                filename=filename,
                local_dir=str(cache_dir),
            )
            self.model_path = Path(resolved_path)
        else:
            self.model_path = Path(model_path)

        if not self.model_path.exists():
            raise FileNotFoundError(f"GGUF model not found at {self.model_path}")

        if n_threads is None:
            import os

            n_threads = max(1, (os.cpu_count() or 4) // 2)

        logger.info(
            "Initializing Llama model from %s (n_ctx=%d, n_threads=%d)...",
            self.model_path,
            n_ctx,
            n_threads,
        )
        self._llm = Llama(
            model_path=str(self.model_path),
            n_ctx=n_ctx,
            n_threads=n_threads,
            verbose=False,
        )
        self._model_name = self.model_path.stem

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        prompt: str,
        temperature: float = 0.1,
        max_tokens: int = 512,
        stop: list[str] | None = None,
    ) -> LLMGenerationResult:
        default_stops = [
            "<|eot_id|>",
            "<|im_end|>",
            "<|end_of_text|>",
            "<|endoftext|>",
            "</answer>",
            "\n\n\n",
        ]
        effective_stop = list(stop) if stop else []
        for s in default_stops:
            if s not in effective_stop:
                effective_stop.append(s)

        # Check if prompt contains system tags for chat formatting
        sys_match = re.search(r"<system>\s*(.*?)\s*</system>", prompt, re.DOTALL)
        user_body = re.sub(r"<system>\s*.*?\s*</system>", "", prompt, flags=re.DOTALL).strip()

        start_time = time.perf_counter()
        prompt_tokens = 0
        completion_tokens = 0

        rep_penalty_env = os.getenv("EASYPASAL_REPETITION_PENALTY")
        rep_penalty = float(rep_penalty_env) if rep_penalty_env else 1.15

        if sys_match:
            sys_text = sys_match.group(1).strip()
            messages: list[Any] = [
                {"role": "system", "content": sys_text},
                {"role": "user", "content": user_body},
            ]
            chat_res: Any = self._llm.create_chat_completion(
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                stop=effective_stop,
                repeat_penalty=rep_penalty,
            )
            if isinstance(chat_res, dict):
                choice = chat_res["choices"][0]
                text = str(choice.get("message", {}).get("content", "")).strip()
                usage = chat_res.get("usage")
                if isinstance(usage, dict):
                    prompt_tokens = int(usage.get("prompt_tokens", 0))
                    completion_tokens = int(usage.get("completion_tokens", 0))
            else:
                text = ""
        else:
            comp_res: Any = self._llm.create_completion(
                prompt=prompt,
                temperature=temperature,
                max_tokens=max_tokens,
                stop=effective_stop,
                stream=False,
                repeat_penalty=rep_penalty,
            )
            if isinstance(comp_res, dict):
                choice = comp_res["choices"][0]
                text = str(choice.get("text", "")).strip()
                usage = comp_res.get("usage")
                if isinstance(usage, dict):
                    prompt_tokens = int(usage.get("prompt_tokens", 0))
                    completion_tokens = int(usage.get("completion_tokens", 0))
            else:
                text = ""

        text = trim_incomplete_sentence(text)

        elapsed = time.perf_counter() - start_time
        latency_ms = round(elapsed * 1000, 2)
        tokens_per_second = (
            round(completion_tokens / elapsed, 2) if elapsed > 0 and completion_tokens > 0 else 0.0
        )

        return LLMGenerationResult(
            text=text,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            latency_ms=latency_ms,
            model_name=self._model_name,
            tokens_per_second=tokens_per_second,
        )

    def close(self) -> None:
        """Close the underlying Llama model and release resources."""
        llm = getattr(self, "_llm", None)
        if llm is not None:
            with contextlib.suppress(Exception):
                llm.close()
            del self._llm
        import gc

        gc.collect()


def _resolve_transformers_model(model_name: str | None) -> str:
    """Resolve model identifier for TransformersBackend, excluding GGUF files/repos."""
    if (
        model_name
        and not model_name.endswith(".gguf")
        and not model_name.endswith("-GGUF")
        and "GGUF" not in model_name
    ):
        return model_name
    return os.getenv("EASYPASAL_TRANSFORMERS_MODEL", DEFAULT_TRANSFORMERS_MODEL)


def _resolve_hf_model(model_name: str | None) -> str:
    """Resolve model identifier for HuggingFaceInferenceBackend, excluding GGUF files/repos."""
    if (
        model_name
        and not model_name.endswith(".gguf")
        and not model_name.endswith("-GGUF")
        and "GGUF" not in model_name
    ):
        return model_name
    return os.getenv("EASYPASAL_HF_MODEL", DEFAULT_HF_MODEL)


def get_generator_backend(
    provider: str = "auto",
    model_name: str | None = None,
    model_path: Path | str | None = None,
    repo_id: str | None = None,
    filename: str | None = None,
    base_url: str | None = None,
    n_ctx: int = 8192,
    n_threads: int | None = None,
) -> GeneratorBackend:
    """Factory creating a generator backend based on available infrastructure.

    Providers:
        - 'transformers': In-process PyTorch/Transformers causal LM (ZeroGPU / CUDA / CPU).
        - 'hf': Hugging Face Serverless Inference API via InferenceClient.
        - 'llamacpp': In-process llama.cpp execution (GGUF).
        - 'ollama': Local Ollama HTTP daemon.
        - 'openai': OpenAI-compatible HTTP endpoint.
        - 'mock': Offline deterministic generator for tests and CI.
        - 'auto': Intelligently selects Transformers (on Spaces/GPU), Ollama, LlamaCpp, or Mock.
    """
    if provider == "mock":
        return MockGeneratorBackend(model_name=model_name or "mock-generator")

    if provider == "transformers":
        return TransformersBackend(
            model_name=_resolve_transformers_model(model_name),
            lazy_load=True,
        )

    if provider == "hf":
        return HuggingFaceInferenceBackend(
            model_name=_resolve_hf_model(model_name),
        )

    if provider == "ollama":
        return OllamaBackend(
            base_url=base_url or "http://localhost:11434",
            model_name=model_name or DEFAULT_OLLAMA_MODEL,
        )

    if provider == "openai":
        return OpenAICompatibleBackend(
            base_url=base_url or "http://localhost:8000/v1",
            model_name=model_name or "local-model",
        )

    if provider == "llamacpp":
        return LlamaCppBackend(
            model_path=model_path,
            repo_id=repo_id or DEFAULT_GGUF_REPO,
            filename=filename or model_name or DEFAULT_GGUF_FILE,
            n_ctx=n_ctx,
            n_threads=n_threads,
        )

    # Provider == 'auto':
    # 1. Check if running inside Hugging Face Spaces
    is_hf_space = bool(os.getenv("SPACE_ID") or os.getenv("SPACE_HOST"))
    if is_hf_space:
        logger.info("Detected Hugging Face Space runtime (%s).", os.getenv("SPACE_ID"))
        try:
            import torch  # noqa: F401
            import transformers  # noqa: F401

            logger.info("Auto-selecting TransformersBackend for Hugging Face Space.")
            return TransformersBackend(
                model_name=_resolve_transformers_model(model_name),
                lazy_load=True,
            )
        except Exception as e:
            logger.warning("Could not initialize TransformersBackend on Space: %s", e)

        hf_token = os.getenv("HF_TOKEN") or os.getenv("HUGGING_FACE_HUB_TOKEN")
        if hf_token:
            try:
                logger.info("Auto-selecting HuggingFaceInferenceBackend with token.")
                return HuggingFaceInferenceBackend(
                    model_name=_resolve_hf_model(model_name),
                    token=hf_token,
                )
            except Exception as e:
                logger.warning("Could not initialize HuggingFaceInferenceBackend on Space: %s", e)

    # 2. Check local Ollama server
    try:
        check_url = (base_url or "http://localhost:11434").rstrip("/") + "/api/tags"
        resp = httpx.get(check_url, timeout=0.8)
        if resp.status_code == 200:
            logger.info("Auto-detected active Ollama service at %s", check_url)
            return OllamaBackend(
                base_url=base_url or "http://localhost:11434",
                model_name=model_name or DEFAULT_OLLAMA_MODEL,
            )
    except Exception:
        pass

    # 3. Check if explicit GGUF path is available on disk
    if model_path and Path(model_path).exists():
        try:
            return LlamaCppBackend(model_path=model_path)
        except Exception as e:
            logger.warning("Failed to initialize LlamaCppBackend: %s", e)

    # 4. Check if HF_TOKEN is present in env for Serverless API
    hf_token = os.getenv("HF_TOKEN") or os.getenv("HUGGING_FACE_HUB_TOKEN")
    if hf_token:
        try:
            return HuggingFaceInferenceBackend(
                model_name=model_name or repo_id or DEFAULT_HF_MODEL,
                token=hf_token,
            )
        except Exception as e:
            logger.warning("Failed to initialize HuggingFaceInferenceBackend: %s", e)

    # Default auto fallback to MockGeneratorBackend
    logger.info("No active local or remote LLM daemon detected; using MockGeneratorBackend.")
    return MockGeneratorBackend(model_name=model_name or "mock-generator")
