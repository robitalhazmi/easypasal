"""Pydantic schemas for structured request logs and user feedback (Plan §9 / Task T7.1)."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class RequestLogRecord(BaseModel):
    """Structured request log record strictly conforming to Plan §9.

    Contains all operational, retrieval, generation, latency, and telemetry fields
    required for production observability, quality monitoring, and audit trails.
    """

    model_config = ConfigDict(extra="forbid")

    request_id: str = Field(
        ...,
        min_length=1,
        description="Unique request tracking identifier (UUID or client-supplied).",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="ISO 8601 UTC timestamp of request execution.",
    )
    variant: str = Field(
        ...,
        min_length=1,
        description="Active pipeline variant ID (e.g. 'baseline_v0.1', 'gepa_v0.2').",
    )
    language: str = Field(
        ...,
        description="Query language ('id' for Indonesian, 'en' for English).",
    )
    question_length: int = Field(
        ...,
        ge=0,
        description="Raw question character length before redaction.",
    )
    question_redacted: str = Field(
        ...,
        description="Sanitized question string with sensitive PII identifiers redacted.",
    )

    # Retrieval Observability
    retrieval_score_top1: float | None = Field(
        default=None,
        description="Relevance score of top-1 retrieved passage chunk, or None if retrieval bypassed.",
    )
    retrieval_scores_topk: list[float] = Field(
        default_factory=list,
        description="Relevance scores of retrieved top-k passage chunks.",
    )
    retrieved_doc_ids: list[str] = Field(
        default_factory=list,
        description="Canonical document identifiers / numbers of candidate passages.",
    )

    # Abstention & Safety Routing
    abstained: bool = Field(
        ...,
        description="Whether the response is an explicit abstention refusal.",
    )
    routed: bool = Field(
        default=False,
        description="Whether query was triaged by the front-line guardrail router.",
    )
    theme: str | None = Field(
        default=None,
        description="Classified statutory regulatory theme (e.g. 'Consumer Protection') or 'Out of Scope'.",
    )

    # Latencies (milliseconds)
    retrieval_latency_ms: float | None = Field(
        default=None,
        ge=0.0,
        description="Passage retrieval latency in milliseconds.",
    )
    generation_latency_ms: float | None = Field(
        default=None,
        ge=0.0,
        description="LLM generation latency in milliseconds.",
    )
    total_latency_ms: float = Field(
        ...,
        ge=0.0,
        description="End-to-end request response duration in milliseconds.",
    )

    # Token Telemetry
    prompt_tokens: int = Field(
        default=0,
        ge=0,
        description="Number of prompt tokens evaluated by the generator backend.",
    )
    completion_tokens: int = Field(
        default=0,
        ge=0,
        description="Number of completion tokens generated by the model.",
    )
    total_tokens: int = Field(
        default=0,
        ge=0,
        description="Aggregate tokens processed across prompt and completion.",
    )

    # Statutory Grounding Verification
    citation_count: int = Field(
        default=0,
        ge=0,
        description="Total statutory citations parsed from the generated answer.",
    )
    grounded_citation_count: int | None = Field(
        default=None,
        ge=0,
        description="Count of citations verified against retrieved passage metadata.",
    )
    ungrounded_citation_count: int | None = Field(
        default=None,
        ge=0,
        description="Count of citations not grounded in retrieved passages (hallucinations).",
    )

    # User Feedback & Analytics
    feedback_rating: int | None = Field(
        default=None,
        description="Optional user feedback rating (+1 positive, -1 negative).",
    )
    feedback_comment: str | None = Field(
        default=None,
        description="Optional sanitized user feedback comment.",
    )
    client_ip_hash: str | None = Field(
        default=None,
        description="Salted one-way hash of client IP address for privacy-safe traffic grouping.",
    )
    model_name: str | None = Field(
        default=None,
        description="Model name/identifier utilized for answer generation.",
    )

    @model_validator(mode="after")
    def compute_total_tokens(self) -> RequestLogRecord:
        if self.total_tokens == 0 and (self.prompt_tokens > 0 or self.completion_tokens > 0):
            self.total_tokens = self.prompt_tokens + self.completion_tokens
        return self


class FeedbackPayload(BaseModel):
    """Payload schema for submitting user feedback on a processed request."""

    model_config = ConfigDict(extra="forbid")

    request_id: str = Field(
        ...,
        min_length=1,
        description="Target request identifier.",
        examples=["b84d9f96-f947-4188-b22a-d944cbb7591e"],
    )
    rating: Literal[1, -1] = Field(
        ...,
        description="User rating (+1 thumbs up / helpful, -1 thumbs down / unhelpful).",
        examples=[1],
    )
    comment: str | None = Field(
        default=None,
        max_length=1000,
        description="Optional free-text feedback comment.",
        examples=["Kutipan pasal akurat dan jelas."],
    )
    tags: list[str] = Field(
        default_factory=list,
        description="Optional categorization tags (e.g. 'wrong_citation', 'helpful', 'incomplete').",
        examples=[["helpful", "accurate_citation"]],
    )


class FeedbackLogRecord(BaseModel):
    """Schema for persisted feedback records."""

    model_config = ConfigDict(extra="forbid")

    request_id: str = Field(..., min_length=1)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    rating: int = Field(..., description="+1 or -1")
    comment_redacted: str | None = None
    tags: list[str] = Field(default_factory=list)
